"""Sync pykissembed's recommended VS Code pytest settings into a consumer project.

Used by ``pykissembed init`` (see :mod:`pykissembed.cli`) to add the two
``python.testing.*`` keys that enable VS Code's Test Explorer on ``tests``.
The checks only appear in the tree via discovery (``--collect-only``); running
the ``tests`` folder does not run them unless a check is selected explicitly.
``.vscode/settings.json`` is JSONC
(comments, trailing commas), which breaks strict :func:`json.loads`, so
values are inspected via a tolerant parse but mutated via targeted text
patches that leave the rest of the file (comments, formatting, unrelated
keys) untouched. :func:`sync_vscode_launch` likewise adds pykissembed's
debug configurations to ``.vscode/launch.json`` without touching existing ones.
"""

from __future__ import annotations

import json
import re
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from pathlib import Path

_DESIRED_SETTINGS: dict[str, object] = {
    "python.testing.pytestArgs": ["tests"],
    "python.testing.pytestEnabled": True,
}
# pytestArgs values written by earlier pykissembed versions; migrated without --force.
_LEGACY_GENERATED_PYTEST_ARGS = (
    ["tests", "--pykissembed-all"],
    ["tests", "--pykissembed-all", "--cached-only"],
)

_DEFAULT_INDENT = "  "

_PYTEST_LAUNCH: dict[str, object] = {
    "type": "debugpy",
    "request": "launch",
    "module": "pytest",
    "cwd": "${workspaceFolder}",
    "console": "integratedTerminal",
    "justMyCode": False,
}
_DEBUG_TEST_PURPOSE = "debug-test"
# Test Explorer's "Debug Test" uses the debug-test config; the other two run
# the gates explicitly, since a plain `tests` run leaves them out.
_LAUNCH_CONFIGS: list[dict[str, object]] = [
    {
        "name": "Pytest: debug test",
        "type": "debugpy",
        "request": "launch",
        "purpose": [_DEBUG_TEST_PURPOSE],
        "console": "integratedTerminal",
        "justMyCode": False,
    },
    {"name": "pykissembed: all gates", **_PYTEST_LAUNCH, "args": ["tests", "--pykissembed-all"]},
    {
        "name": "pykissembed: docstring and comment audits",
        **_PYTEST_LAUNCH,
        "args": ["tests", "-m", "docstring_format or jev"],
    },
]


def sync_vscode_settings(root: Path, *, force: bool) -> list[str]:
    """Create or update ``.vscode/settings.json`` with pykissembed's pytest settings.

    Parameters
    ----------
    root
        Project root (the directory containing, or to contain, ``.vscode/``).
    force
        If ``True``, overwrite keys that already exist with a conflicting
        value. If ``False``, conflicting keys are left untouched, except for
        the exact pytest arguments generated by older pykissembed versions
        (which forced ``--pykissembed-all``), which are migrated to the
        current defaults.

    Returns
    -------
    list[str]
        One human-readable status message per key (or a single warning if
        the existing file could not be parsed).
    """
    vscode_dir = root / ".vscode"
    settings_path = vscode_dir / "settings.json"

    if not settings_path.exists():
        vscode_dir.mkdir(exist_ok=True)
        _ = settings_path.write_text(_render_fresh_file())
        return [f"Added {key} to .vscode/settings.json." for key in _DESIRED_SETTINGS]

    text = settings_path.read_text()
    current = _tolerant_parse(text)
    if current is None:
        return [
            "Could not parse .vscode/settings.json as JSON/JSONC; leaving it "
            "untouched. Add manually: "
            + ", ".join(f"{k}={json.dumps(v)}" for k, v in _DESIRED_SETTINGS.items()),
        ]

    messages: list[str] = []
    for key, desired in _DESIRED_SETTINGS.items():
        if key in current and current[key] == desired:
            messages.append(f"{key} already in sync in .vscode/settings.json.")
            continue
        if key == "python.testing.pytestArgs" and current.get(key) in _LEGACY_GENERATED_PYTEST_ARGS:
            text = _patch_key(text, key, desired)
            current[key] = desired
            messages.append(
                "Migrated python.testing.pytestArgs in .vscode/settings.json "
                "(removed --pykissembed-all; checks now run only when explicitly requested).",
            )
            continue
        if key in current and not force:
            messages.append(
                f"{key} already set to a different value in .vscode/settings.json. "
                "Use --force to overwrite.",
            )
            continue
        text = _patch_key(text, key, desired)
        verb = "Updated" if key in current else "Added"
        suffix = " (--force)." if key in current and force else "."
        messages.append(f"{verb} {key} in .vscode/settings.json{suffix}")

    _ = settings_path.write_text(text)
    return messages


def sync_vscode_launch(root: Path) -> list[str]:
    """Add pykissembed's debug configurations to ``.vscode/launch.json``.

    Existing configurations are never changed. A pykissembed configuration
    is skipped when one with its name exists, and the debug-test one also
    when another configuration already claims the ``debug-test`` purpose.

    Parameters
    ----------
    root
        Project root (the directory containing, or to contain, ``.vscode/``).

    Returns
    -------
    list[str]
        One human-readable status message.
    """
    vscode_dir = root / ".vscode"
    launch_path = vscode_dir / "launch.json"
    if not launch_path.exists():
        vscode_dir.mkdir(exist_ok=True)
        launch = {"version": "0.2.0", "configurations": _LAUNCH_CONFIGS}
        _ = launch_path.write_text(json.dumps(launch, indent=_DEFAULT_INDENT) + "\n")
        return [f"Added {len(_LAUNCH_CONFIGS)} configurations to .vscode/launch.json."]

    text = launch_path.read_text()
    current = _tolerant_parse(text)
    existing = current.get("configurations") if current is not None else None
    anchor = re.search(r'"configurations"\s*:\s*\[', text)
    if not isinstance(existing, list) or anchor is None:
        return [
            "Could not find a configurations list in .vscode/launch.json; leaving it "
            "untouched. Add manually: " + json.dumps(_LAUNCH_CONFIGS),
        ]

    missing = _missing_launch_configs([c for c in existing if isinstance(c, dict)])
    if not missing:
        return [".vscode/launch.json configurations already in sync."]
    # Prepend right after `[` so comments and formatting elsewhere survive;
    # a comma is only needed when user configurations follow ours.
    rendered = _render_launch_configs(missing, _detect_indent(text))
    trailing_comma = "," if existing else ""
    text = text[: anchor.end()] + rendered + trailing_comma + text[anchor.end() :]
    _ = launch_path.write_text(text)
    return [f"Added {len(missing)} configurations to .vscode/launch.json."]


def _render_launch_configs(configs: list[dict[str, object]], unit: str) -> str:
    """Serialise *configs* as comma-separated array elements.

    Parameters
    ----------
    configs : list[dict[str, object]]
        Launch configurations to render.
    unit : str
        The file's indentation unit.

    Returns
    -------
    str
        Each configuration on its own lines, indented two levels deep
        (inside the top-level object and the ``configurations`` array).
    """
    blocks = (json.dumps(config, indent=unit).splitlines() for config in configs)
    return ",".join("\n" + "\n".join(unit * 2 + line for line in block) for block in blocks)


def _missing_launch_configs(existing: list[dict[str, object]]) -> list[dict[str, object]]:
    """Return the pykissembed launch configurations *existing* lacks.

    Parameters
    ----------
    existing : list[dict[str, object]]
        Configurations already in ``launch.json``.

    Returns
    -------
    list[dict[str, object]]
        Entries of :data:`_LAUNCH_CONFIGS` whose name is absent, minus the
        debug-test entry when another configuration already has that purpose.
    """
    names = {c.get("name") for c in existing}
    # VS Code uses only one debug-test config, so a user's own takes precedence.
    has_debug_test = any(
        isinstance(purpose := c.get("purpose"), list) and _DEBUG_TEST_PURPOSE in purpose
        for c in existing
    )
    return [
        c
        for c in _LAUNCH_CONFIGS
        if c["name"] not in names and not (has_debug_test and "purpose" in c)
    ]


def _render_fresh_file() -> str:
    """Render a brand-new ``settings.json`` containing only the desired keys.

    Returns
    -------
    str
        A minimal JSON document (with a trailing newline) holding exactly
        :data:`_DESIRED_SETTINGS`, ready to write to a new file.
    """
    lines = [
        f'{_DEFAULT_INDENT}"{key}": {json.dumps(value)}' for key, value in _DESIRED_SETTINGS.items()
    ]
    return "{\n" + ",\n".join(lines) + "\n}\n"


def _tolerant_parse(text: str) -> dict[str, object] | None:
    """Strip JSONC comments/trailing commas and parse for inspection only.

    The stripped text is only used to read current key values; mutations
    are applied to the original ``text`` via :func:`_patch_key` so that
    comments and formatting elsewhere in the file survive untouched.

    Parameters
    ----------
    text : str
        Raw ``settings.json`` text, possibly JSONC.

    Returns
    -------
    dict[str, object] | None
        The parsed top-level object, or ``None`` if the file isn't valid
        JSON/JSONC (or isn't an object) even after stripping.
    """
    no_line_comments = re.sub(r"//[^\n]*", "", text)
    no_block_comments = re.sub(r"/\*.*?\*/", "", no_line_comments, flags=re.DOTALL)
    no_trailing_commas = re.sub(r",(\s*[}\]])", r"\1", no_block_comments)
    try:
        data = json.loads(no_trailing_commas)
    except json.JSONDecodeError:
        return None
    if not isinstance(data, dict):
        return None
    return data


def _patch_key(text: str, key: str, value: object) -> str:
    """Replace an existing ``key``'s value, or insert ``key`` after the opening brace.

    Parameters
    ----------
    text : str
        Original ``settings.json`` text to edit.
    key : str
        Setting key to set.
    value : object
        JSON-serialisable value to assign.

    Returns
    -------
    str
        ``text`` with ``key`` set to ``value``.
    """
    escaped_key = re.escape(key)
    value_text = json.dumps(value)
    # _DESIRED_SETTINGS values are always a flat string list, bool, or number
    # (never nested), so matching up to the first unmatched `]`/literal
    # boundary is enough -- no need for a full JSON-aware value scanner.
    existing_pattern = re.compile(
        rf'"{escaped_key}"\s*:\s*(\[[^\]]*\]|"[^"]*"|true|false|-?\d+(?:\.\d+)?)'
    )
    if existing_pattern.search(text):
        return existing_pattern.sub(f'"{key}": {value_text}', text, count=1)
    return _insert_key(text, key, value_text)


def _insert_key(text: str, key: str, value_text: str) -> str:
    """Insert a new ``key: value_text`` property right after the opening ``{``.

    Parameters
    ----------
    text : str
        Original ``settings.json`` text to edit.
    key : str
        Setting key to insert.
    value_text : str
        Already-serialised JSON text for the value.

    Returns
    -------
    str
        ``text`` with the new property inserted, or ``text`` unchanged if
        it has no top-level ``{`` at all.
    """
    brace_match = re.search(r"\{", text)
    if brace_match is None:
        return text
    insert_at = brace_match.end()
    indent = _detect_indent(text)
    # A comma is only needed when other properties still follow the
    # insertion point; inserting into an otherwise-empty `{}` must not
    # leave a dangling trailing comma before the closing brace.
    has_more_content = bool(text[insert_at:].strip().rstrip("}").strip())
    trailing_comma = "," if has_more_content else ""
    new_property = f'\n{indent}"{key}": {value_text}{trailing_comma}'
    return text[:insert_at] + new_property + text[insert_at:]


def _detect_indent(text: str) -> str:
    """Infer the file's indentation unit from its first indented line.

    Parameters
    ----------
    text : str
        File text to infer the indentation unit from.

    Returns
    -------
    str
        The whitespace prefix of the first indented line, or two spaces
        (VS Code's default) if the file has no indented lines at all.
    """
    match = re.search(r"\n([ \t]+)\S", text)
    return match.group(1) if match else _DEFAULT_INDENT
